import { Router } from 'express';
import { z } from 'zod';
import { getAuth, requireAuth } from '../../middleware/auth.js';
import { chatLimiter } from '../../middleware/rateLimit.js';
import { input, validate } from '../../middleware/validate.js';
import * as chat from './chat.service.js';

export const MAX_MESSAGE_LENGTH = 1000;

const SessionParams = z.object({ sessionId: z.uuid('Invalid conversation id') });

const MessagesQuery = z.object({
  limit: z.coerce.number().int().min(1).max(100).default(50),
  before: z.string().regex(/^\d+$/, 'Invalid cursor').optional(),
});

const SendMessageBody = z.object({
  content: z
    .string({ error: 'Message cannot be empty' })
    .trim()
    .min(1, 'Message cannot be empty')
    .max(MAX_MESSAGE_LENGTH, `Messages are limited to ${MAX_MESSAGE_LENGTH} characters`),
  /** Idempotency key generated by the client. */
  clientMessageId: z.uuid().optional(),
});

export const chatRouter = Router();
chatRouter.use(requireAuth);

chatRouter.get('/sessions', async (req, res) => {
  res.json({ sessions: await chat.listSessions(getAuth(req)) });
});

chatRouter.post('/sessions', async (req, res) => {
  res.status(201).json(await chat.createSession(getAuth(req)));
});

chatRouter.get('/sessions/:sessionId', validate({ params: SessionParams }), async (req, res) => {
  const { sessionId } = input<typeof SessionParams>(req, 'params');
  res.json({ session: await chat.getSession(getAuth(req), sessionId) });
});

chatRouter.get('/sessions/:sessionId/messages', validate({ params: SessionParams, query: MessagesQuery }), async (req, res) => {
  const { sessionId } = input<typeof SessionParams>(req, 'params');
  const query = input<typeof MessagesQuery>(req, 'query');
  const messages = await chat.listMessages(getAuth(req), sessionId, query);
  res.json({ messages, nextCursor: messages.length === query.limit ? messages[0]?.id ?? null : null });
});

chatRouter.post(
  '/sessions/:sessionId/messages',
  chatLimiter,
  validate({ params: SessionParams, body: SendMessageBody }),
  async (req, res) => {
    const { sessionId } = input<typeof SessionParams>(req, 'params');
    const body = input<typeof SendMessageBody>(req, 'body');
    res.status(201).json(await chat.sendMessage(getAuth(req), sessionId, body));
  },
);

chatRouter.post('/sessions/:sessionId/confirm', chatLimiter, validate({ params: SessionParams }), async (req, res) => {
  const { sessionId } = input<typeof SessionParams>(req, 'params');
  res.status(201).json(await chat.confirmBooking(getAuth(req), sessionId));
});
